# In ra màn hình dãy số từ 1 đến 20.

print('Dùng for:')
for i in range(1,21,1):
    print(i,end=' ')

print() # Xuống hàng
print('Dùng while:')
i = 1
while i < 21:
    print(i,end=' ')
    i += 1

